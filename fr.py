from blog_writing_crew.crew import BlogWritingCrew
import streamlit as st


st.title("Enter your blog title of the topic you like ")
blog_title = st.text_input("Enter below")


if st.button("Generate blog"):
    if blog_title:
        st.write("Blog is getting generated")

        inputs  = {
          "topic" : blog_title,
          "current_year": "2026"
                   }
        with st.spinner("Ai agents to your work"):
             result = BlogWritingCrew().crew().kickoff(inputs=inputs)
        st.success("Blog generated !")
        st.divider()
        st.subheader(f"{blog_title}")
        st.caption("Generated by your ai writing team")
        with st.container(border = True):
          st.markdown(result.raw)
        st.download_button(
    label="Download blog",
    data=result.raw,
    file_name="my_blog.md",
    mime="text/markdown"
)
    else:
        st.warning("Please enter a type")


